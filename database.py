    def add_comment(self, user_id, content_id, text, stage=None):
        """إضافة تعليق مرتبط بمحتوى محدد مع فحص بسيط لمنع السبام."""
        if not self.can_user_comment(user_id):
            return None

        with self._lock:
            def mutate(comments):
                comment_id = max([c.get('id', 0) for c in comments], default=0) + 1
                comments.append({'id': comment_id, 'user_id': user_id, 'content_id': content_id,
                                 'text': text, 'stage': stage, 'date': datetime.now().isoformat()})
                return comment_id
            comment_id = self._mutate_data('comments', mutate)
            def update_meta(meta):
                record = meta.get(str(content_id), {'count': 0})
                record['count'] = record.get('count', 0) + 1
                meta[str(content_id)] = record
            self._mutate_data('comments_meta', update_meta)
            return comment_id

