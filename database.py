    def search_content(self, query, stage=None, limit=20):
        """Search in PostgreSQL/SQLite instead of loading all content into Python."""
        limit = max(1, min(int(limit), 100))
        terms = [term for term in query.split() if len(term) > 1]
        if terms:
            clauses = []
            params = []
            for term in terms:
                operator = 'ILIKE' if self._backend == 'postgresql' else 'LIKE'
                clauses.append(f"(c.description {operator} ? OR c.body {operator} ? OR c.file_name {operator} ? OR s.name_ar {operator} ?)")
                params.extend([f'%{term}%'] * 4)
            where = ' AND '.join(clauses)
            if stage is not None:
                where = 'c.stage = ? AND ' + where
                params.insert(0, stage)
            params.append(limit)
            rows = self._execute(
                f'''SELECT c.id, c.stage, c.subject_key, c.chapter, c.content_type,
                           c.file_id, c.file_name, c.body, c.description, c.content_number,
                           c.added_by, s.name_ar
                    FROM content c JOIN subjects s ON (s.stage=c.stage AND s.subject_key=c.subject_key)
                    WHERE {where} ORDER BY c.id DESC LIMIT ?''', params).fetchall()
            if rows:
                return [(
                    {'id': row[0], 'stage': row[1], 'subject_key': row[2], 'chapter_num': row[3],
                     'content_type': row[4], 'file_id': row[5], 'file_name': row[6], 'text': row[7],
                     'description': row[8], 'content_number': row[9], 'added_by': row[10]}, row[11]
                ) for row in rows]

        # Compatibility fallback for data created before the first migration.
        words = [x for x in query.lower().split() if len(x) > 1]
        subjects = {(x['stage'], x['key']): x['name_ar'] for x in self._read_data('subjects')}
        matches = []
        for content in self._read_data('stage_content'):
            if stage and content.get('stage') != stage:
                continue
            subject_name = subjects.get((content.get('stage'), content.get('subject_key')), '')
            haystack = ' '.join(str(content.get(k) or '') for k in ('description', 'text', 'file_name', 'content_type'))
            haystack = f'{haystack} {subject_name}'.lower()
            score = sum(1 for word in words if word in haystack)
            if score:
                matches.append((score, content, subject_name))
        matches.sort(key=lambda x: (x[0], x[1].get('date_added', '')), reverse=True)
        return [(x[1], x[2]) for x in matches[:limit]]

