    def record_quiz_attempt(self, user_id, quiz_id, answer_index):
        with self._lock:
            quiz = self.get_quiz(quiz_id)
            if not quiz or not isinstance(quiz.get('options'), list) or answer_index not in range(len(quiz['options'])):
                return None
            correct = answer_index == quiz.get('correct_index')
            def mutate(attempts):
                attempts.append({'user_id': user_id, 'quiz_id': quiz_id, 'answer_index': answer_index, 'correct': correct, 'created_at': datetime.now().isoformat()})
            self._mutate_data('quiz_attempts', mutate)
            return correct

